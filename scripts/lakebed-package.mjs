import { readdir, readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { extname } from 'node:path';

// Encode the verified offline build for Lakebed's single-client artifact.
const folder = '.build-offline/site';
const mime = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.gif': 'image/gif', '.png': 'image/png', '.json': 'application/json', '.md': 'text/plain' };
const files = [];
async function walk(directory = '') {
  for (const entry of await readdir(`${folder}/${directory}`, { withFileTypes: true })) {
    const path = directory ? `${directory}/${entry.name}` : entry.name;
    if (entry.isDirectory()) { await walk(path); continue; }
    if (path.endsWith('.zip') || (path.startsWith('assets/') && path.endsWith('.js'))) continue;
    const bytes = await readFile(`${folder}/${path}`);
    files.push({ path, type: mime[extname(path)] || 'text/plain', gzip: gzipSync(bytes, { level: 9 }).toString('base64') });
  }
}
await walk();
await writeFile('lakebed/neo-geo-bootstrap/shared/site.ts', `// Generated by npm run build:lakebed. Edit the original theme/demo sources.\nexport const files = ${JSON.stringify(files)} as const;\n`);
console.log(`Prepared ${files.length} self-contained files for Lakebed.`);
